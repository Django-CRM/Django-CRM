class OrgProfileCreateView(APIView):
    permission_classes = (IsAuthenticated,)

    model1 = Org
    model2 = Profile
    serializer_class = OrgProfileCreateSerializer
    profile_serializer = CreateProfileSerializer

    @extend_schema(
        operation_id="org_create",
        description="Organization and profile Creation api",
        request=OrgProfileCreateSerializer,
    )
    def post(self, request, format=None):
        # The org's API key is generated by the model
        # (`Org.api_key`, `default=generate_unique_key`, `editable=False`), not
        # here. This method used to write a `secrets.token_hex(16)` into the
        # request body first, which the serializer then discarded because
        # `api_key` is not in its `fields`. Nothing read it, and it made anyone
        # auditing where org keys come from read the wrong line.
        serializer = self.serializer_class(data=request.data)
        if serializer.is_valid():
            org_obj = serializer.save()

            # now creating the profile
            profile_obj = self.model2.objects.create(user=request.user, org=org_obj)
            # now the current user is the admin of the newly created organisation.
            # `is_organization_admin` is derived from `role` in `Profile.save`.
            profile_obj.role = "ADMIN"
            profile_obj.save()

            return Response(
                {
                    "error": False,
                    "message": "New Org is Created.",
                    # The creator's membership facts ride on the org, in the
                    # shape the auth endpoints use for each org they list, so a
                    # client caching this org gates admin UI correctly at once.
                    # Server-derived; nothing here is read from the request.
                    "org": {
                        **self.serializer_class(org_obj).data,
                        "role": profile_obj.role,
                        "is_organization_admin": is_org_admin(profile_obj),
                    },
                    "status": status.HTTP_201_CREATED,
                },
                status=status.HTTP_201_CREATED,
            )
        return Response(
            {
                "error": True,
                "errors": serializer.errors,
            },
            status=status.HTTP_400_BAD_REQUEST,
        )

    @extend_schema(
        operation_id="org_list",
        description="Just Pass the token, will return ORG list, associated with user",
    )
    def get(self, request, format=None):
        """
        here we are passing profile list of the user, where org details also included
        """
        profile_list = Profile.objects.filter(user=request.user).select_related(
            "org", "user"
        )
        serializer = ShowOrganizationListSerializer(profile_list, many=True)
        return Response(
            {
                "error": False,
                "status": status.HTTP_200_OK,
                "profile_org_list": serializer.data,
            }
        )


class OrgUpdateView(APIView):
    """Read and rename the caller's own organization.

    Narrow on purpose: `OrganizationSerializer` is `(id, name)`, so `name` is
    the only thing this endpoint has ever written. The company profile, locale
    and behaviour switches are edited through `OrgSettingsView`
    (`/api/org/settings/`), which is what the web app uses. Two write paths
    over the same row is not a shape worth extending, so this one is left at
    the field it already had rather than grown into a second settings
    endpoint.

    The org id comes from the URL and is checked against `request.profile.org`
    before anything is read or written, so a caller can only ever reach their
    own org.
    """

    permission_classes = (IsAuthenticated,)

    def _org_or_error(self, request, pk, *, verb="update"):
        """Return (org, None) for an admin of this org, or (None, Response)."""
        if not request.profile:
            return None, Response(
                {"error": True, "errors": "Organization context required"},
                status=status.HTTP_400_BAD_REQUEST,
            )

        if str(request.profile.org.id) != str(pk):
            return None, Response(
                {"error": True, "errors": f"Cannot {verb} a different organization"},
                status=status.HTTP_403_FORBIDDEN,
            )

        if verb == "update" and not is_org_admin(request.profile):
            return None, Response(
                {
                    "error": True,
                    "errors": "Only organization admins can update organization details",
                },
                status=status.HTTP_403_FORBIDDEN,
            )

        org = Org.objects.filter(id=pk).first()
        if org is None:
            return None, Response(
                {"error": True, "errors": "Organization not found"},
                status=status.HTTP_404_NOT_FOUND,
            )

        return org, None

    def _write(self, request, pk, *, partial):
        """PUT and PATCH, which differed only in the word "Partial" in a comment.

        Both used to assign `request.data["name"]` straight to the column with
        no validation at all. `Org.name` is `varchar(100)`, so a longer name
        reached PostgreSQL as a `DataError` and the caller got a 500 with no
        indication of which field was wrong. The serializer carries the
        model's own `max_length`, which is the whole reason to route through
        one, per the API Validation rules in CLAUDE.md.
        """
        org, error = self._org_or_error(request, pk)
        if error:
            return error

        update = OrganizationSerializer(org, data=request.data, partial=partial)
        if not update.is_valid():
            return Response(
                {"error": True, "errors": update.errors},
                status=status.HTTP_400_BAD_REQUEST,
            )
        update.save()

        return Response(
            {
                "error": False,
                "message": "Organization updated successfully",
                "org": update.data,
            },
            status=status.HTTP_200_OK,
        )

    @extend_schema(
        operation_id="org_update",
        description="Rename the caller's organization",
        request=OrganizationSerializer,
        responses={200: OrganizationSerializer},
    )
    def put(self, request, pk, format=None):
        # `name` is `blank=True, null=True` on the model, so DRF makes it
        # optional and a PUT without it is a no-op rather than a 400. That is
        # what this endpoint already did; changing it would break clients that
        # send the whole record back.
        return self._write(request, pk, partial=False)

    @extend_schema(
        # Was `org_destroy`, on the PATCH handler. A generated client turned
        # that into a `destroy()` method that performed a partial update, and
        # the description right below it said "Partial update" at the same
        # time. Nothing on this view deletes anything.
        operation_id="org_partial_update",
        description="Partially update the caller's organization",
        request=OrganizationSerializer,
        responses={200: OrganizationSerializer},
    )
    def patch(self, request, pk, format=None):
        return self._write(request, pk, partial=True)

    @extend_schema(
        operation_id="org_retrieve",
        description="Get organization details",
        responses={200: OrganizationSerializer},
    )
    def get(self, request, pk, format=None):
        # Read is open to every member of the org, so no role check here; the
        # org match in `_org_or_error` is the boundary that matters.
        org, error = self._org_or_error(request, pk, verb="access")
        if error:
            return error

        return Response(
            {"error": False, "org": OrganizationSerializer(org).data},
            status=status.HTTP_200_OK,
        )


class OrgApiKeyView(APIView):
    """Read and rotate the org API key. Admins only.

    The key authenticates its bearer as the org's first ADMIN profile, so it is
    kept out of every nested representation (see `OrganizationSerializer`) and
    served only here. The org is always taken from `request.profile` -- never
    from a client-supplied id -- so a caller can only ever reach their own.
    """

    permission_classes = (IsAuthenticated,)

    def _admin_org_or_error(self, request):
        """Return (org, None) for org admins, or (None, error Response)."""
        if not request.profile:
            return None, Response(
                {"error": True, "errors": "Organization context required"},
                status=status.HTTP_400_BAD_REQUEST,
            )

        if not is_org_admin(request.profile):
            return None, Response(
                {
                    "error": True,
                    "errors": "Only organization admins can access the API key",
                },
                status=status.HTTP_403_FORBIDDEN,
            )

        return request.profile.org, None

    @extend_schema(
        operation_id="org_api_key_retrieve",
        description="Retrieve the current organization's API key (admins only)",
        parameters=swagger_params.organization_params,
        responses={
            200: inline_serializer(
                name="OrgApiKeyResponse",
                fields={"api_key": serializers.CharField()},
            )
        },
    )
    def get(self, request, format=None):
        org, error = self._admin_org_or_error(request)
        if error:
            return error

        return Response(
            {"error": False, "api_key": org.api_key},
            status=status.HTTP_200_OK,
        )

    @extend_schema(
        operation_id="org_api_key_rotate",
        description=(
            "Rotate the current organization's API key (admins only). "
            "The previous key stops authenticating immediately."
        ),
        parameters=swagger_params.organization_params,
        responses={
            200: inline_serializer(
                name="OrgApiKeyRotateResponse",
                fields={"api_key": serializers.CharField()},
            )
        },
    )
    def post(self, request, format=None):
        org, error = self._admin_org_or_error(request)
        if error:
            return error

        org.api_key = secrets.token_urlsafe(32)
        org.save(update_fields=["api_key"])

        return Response(
            {
                "error": False,
                "message": "API key rotated. The previous key is no longer valid.",
                "api_key": org.api_key,
            },
            status=status.HTTP_200_OK,
        )


class ProfileView(APIView):
    permission_classes = (IsAuthenticated,)

    @extend_schema(
        tags=["profile"],
        parameters=swagger_params.organization_params,
        responses={
            200: inline_serializer(
                name="ProfileViewResponse", fields={"user_obj": ProfileSerializer()}
            )
        },
    )
    def get(self, request, format=None):
        # request.profile is set by middleware from the JWT's org claim. Without
        # org context there is no profile to return; answer 400 rather than
        # serialize None into an empty object that looks like a real one.
        profile = request.profile
        if profile is None:
            return Response(
                {"error": "Organization context required"},
                status=status.HTTP_400_BAD_REQUEST,
            )
        user_obj = ProfileSerializer(profile).data
        # The page shows which teams the current user is on. Teams is a real
        # Profile.user_teams m2m, but it is not on the shared ProfileSerializer
        # (nested into many records). Adding it here keeps the extra query and
        # the wider output on this one self-profile endpoint, off the hot path.
        user_obj["teams"] = list(profile.user_teams.values_list("name", flat=True))
        return Response({"user_obj": user_obj}, status=status.HTTP_200_OK)

    @extend_schema(
        tags=["profile"],
        parameters=swagger_params.organization_params,
        request=ProfileSelfUpdateSerializer,
        responses={
            200: inline_serializer(
                name="ProfilePatchUpdateResponse",
                fields={
                    "message": serializers.CharField(),
                    "user_obj": ProfileSerializer(),
                },
            )
        },
    )
    def patch(self, request, format=None):
        profile = request.profile
        if profile is None:
            return Response(
                {"error": "Organization context required"},
                status=status.HTTP_400_BAD_REQUEST,
            )

        # Validate through a serializer that names ONLY phone and name. A bad
        # phone is now a clean 400 (the old code wrote request.data straight to
        # the column), and, more importantly, role/org/access flags are not
        # fields here, so no request body can escalate a profile through this
        # self-edit door. See ProfileSelfUpdateSerializer.
        update = ProfileSelfUpdateSerializer(data=request.data, partial=True)
        update.is_valid(raise_exception=True)
        data = update.validated_data

        # Update phone on Profile if provided
        if "phone" in data:
            profile.phone = data["phone"]
            profile.save(update_fields=["phone"])

        # Update name on User if provided. Name lives on User (not Profile) so
        # it's shared across all org memberships for the same user.
        if "name" in data:
            user = request.user
            user.name = data["name"].strip()
            user.save(update_fields=["name"])

        return Response(
            {
                "message": "Profile updated successfully",
                "user_obj": ProfileSerializer(profile).data,
            },
            status=status.HTTP_200_OK,
        )


class ProfileDetailView(APIView):
    """The caller's own profile in whichever org their token names.

    It used to say "Requires org header", and published that header as a
    required parameter, and its 400 body told the caller to send one. There is
    no org header: `common/middleware/get_company.py` derives the org from the
    JWT's `org_id` claim, the PAT, or the API key. A caller following the
    documented instruction would have added a header, seen no change, and had
    no way to tell why.
    """

    authentication_classes = [JWTAuthentication]
    permission_classes = [IsAuthenticated]

    @extend_schema(
        description=(
            "Profile for the current user in the organization their token "
            "names. Org context comes from the token, not from a parameter."
        ),
        responses={200: serializer.ProfileDetailSerializer},
    )
    def get(self, request):
        # Set by middleware from the token's org claim. Absent means the token
        # carries no org, which is what `/api/org/` is for.
        if not hasattr(request, "profile") or request.profile is None:
            return Response(
                {"error": "Organization context required"},
                status=status.HTTP_400_BAD_REQUEST,
            )

        profile_serializer = serializer.ProfileDetailSerializer(request.profile)
        return Response(profile_serializer.data, status=status.HTTP_200_OK)
